//Literal (General): A literal is a fixed value assigned directly to a variable in a program


class BasicsDemo {
    public static void main(String[] args) {
        int decimal = 10;        // Decimal literal
        int binary = 0b1010;     // Binary literal
        int octal = 012;         // Octal literal
        int hex = 0xA;           // Hexadecimal literal

        float f = 5.5f;          // Float literal
        double d = 10.25;        // Double literal
        char ch = 'A';           // Character literal
        String str = "Rahul";    // String literal
        boolean flag = true;     // Boolean literal

        System.out.println("Decimal: " + decimal);
        System.out.println("Binary: " + binary);
        System.out.println("Octal: " + octal);
        System.out.println("Hex: " + hex);
        System.out.println("Float: " + f);
        System.out.println("Double: " + d);
        System.out.println("Char: " + ch);
        System.out.println("String: " + str);
        System.out.println("Boolean: " + flag);
    }
    }